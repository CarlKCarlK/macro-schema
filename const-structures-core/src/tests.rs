#[test]
fn define_documents_members_and_blocks() -> Result<()> {
    let schema: Schema = syn::parse_str(STRIPS_SCHEMA)?;
    let doc = macro_doc(&syn::parse_quote!(strips), &schema.body)?;
    let expected = "\n\n**Syntax:**\n\n```text\n\
        strips! {\n    [<attributes>] [<visibility>] <Name> {\n\
        \x20       bus: <ident>, // optional, default: BUS0\n\
        \x20       [<attributes>] <MemberName> { // 1 to 2 members; visibility comes from the group\n\
        \x20           pin: <ident>,\n\
        \x20           dma: <ident>, // optional, default: by member index: DMA0, DMA1\n\
        \x20           panel: { // optional\n\
        \x20               width: <expr>,\n\
        \x20               font: <expr>, // optional, default: Font::Small\n\
        \x20           },\n\
        \x20       },\n\
        \x20   }\n}\n```\n\n**Fields:**\n\n\
        | Field | Kind | Default | Description |\n\
        | ----- | ---- | ------- | ----------- |\n\
        | `bus` | ident | `BUS0` | Shared bus. |\n\
        \n**Member fields** (1 to 2 members; One strip per member.):\n\n\
        | Field | Kind | Default | Description |\n\
        | ----- | ---- | ------- | ----------- |\n\
        | `pin` | ident | required | Data pin. |\n\
        | `dma` | ident | by member index: `DMA0`, `DMA1` | Channel. |\n\
        | `panel` | block | optional | Optional panel geometry. |\n\
        | `panel.width` | expr | required | Width in pixels. |\n\
        | `panel.font` | expr | `Font::Small` | Font. |\n";
    assert_eq!(expected, doc);
    Ok(())
}

#[test]
fn default_display_overrides_docs_but_not_generated_tokens() -> Result<()> {
    let schema_source = "__gen {
        /// Color curve.
        #[default_display = \"Gamma::Srgb\"]
        gamma: expr = ::demo::led_strip::Gamma::Srgb,
    }";
    let schema: Schema = syn::parse_str(schema_source)?;
    let doc = macro_doc(&syn::parse_quote!(led), &schema.body)?;
    assert!(doc.contains("gamma: <expr>, // optional, default: Gamma::Srgb\n"));
    assert!(doc.contains("| `gamma` | expr | `Gamma::Srgb` | Color curve. |\n"));
    let instance_doc = "Generated by `led!`.\n\n\
        | Field | Value |\n| ----- | ----- |\n\
        | `gamma` | `Gamma::Srgb` (default) |\n";
    let expected = quote! {
        __gen! {
            attrs: [],
            vis: [pub(self)],
            name: Strip,
            doc: #instance_doc,
            gamma: ::demo::led_strip::Gamma::Srgb,
        }
    };
    assert_eq!(
        pretty(expected)?,
        pretty(run(schema_source, "led", quote! { Strip {} })?)?
    );
    Ok(())
}

