const STRIPS_SCHEMA: &str = "__strips_generate {
    /// Shared bus.
    bus: ident = BUS0,
    /// One strip per member.
    members 1..=2 {
        /// Data pin.
        pin: ident,
        /// Channel.
        dma: ident = by_index[DMA0, DMA1],
        /// Optional panel geometry.
        panel?: {
            /// Width in pixels.
            width: expr,
            /// Font.
            font: expr = Font::Small,
        },
    },
}";

#[test]
fn expand_members_with_index_defaults_and_optional_block() -> Result<()> {
    let input = quote! {
        pub Strips {
            First { pin: P0 },
            Second { panel: { width: 12 }, pin: P1 },
        }
    };
    let group_doc = "Generated by `strips!`.\n\n\
        | Field | Value |\n| ----- | ----- |\n\
        | `bus` | `BUS0` (default) |\n\
        \nMembers: `First`, `Second`.\n";
    let first_doc = "Member `First` of `Strips`, generated by `strips!`.\n\n\
        | Field | Value |\n| ----- | ----- |\n\
        | `pin` | `P0` |\n\
        | `dma` | `DMA0` (default) |\n\
        | `panel` | `(not set)` |\n";
    let second_doc = "Member `Second` of `Strips`, generated by `strips!`.\n\n\
        | Field | Value |\n| ----- | ----- |\n\
        | `pin` | `P1` |\n\
        | `dma` | `DMA1` (default) |\n\
        | `panel` | `{ width: 12, font: Font::Small }` |\n";
    let expected = quote! {
        __strips_generate! {
            attrs: [],
            vis: [pub],
            name: Strips,
            doc: #group_doc,
            bus: BUS0,
            member_count: 2,
            members: [
                {
                    index: 0,
                    attrs: [],
                    vis: [pub],
                    name: First,
                    doc: #first_doc,
                    pin: P0,
                    dma: DMA0,
                    panel: [],
                },
                {
                    index: 1,
                    attrs: [],
                    vis: [pub],
                    name: Second,
                    doc: #second_doc,
                    pin: P1,
                    dma: DMA1,
                    panel: [{ width: 12, font: Font::Small, }],
                },
            ],
        }
    };
    assert_eq!(
        pretty(expected)?,
        pretty(run(STRIPS_SCHEMA, "strips", input)?)?
    );
    Ok(())
}

