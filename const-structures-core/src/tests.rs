#[test]
fn template_matcher_covers_kinds_metadata_and_repetition_depths() -> Result<()> {
    let schema: Schema = syn::parse2(quote! {
        __generate {
            name: ident,
            value?: expr,
            output: ty,
            bounds: { min: expr, max: expr },
            members 1.. {
                name: ident,
                index: expr = 0,
                limits?: { min: expr, upper?: expr },
            },
        }
    })?;
    let expected = quote! {
        attrs: [$(#[$attrs:meta])*],
        vis: [$vis:vis],
        name: $name:ident,
        doc: $doc:literal,
        name: $field_name:ident,
        value: [$($field_value:expr)?],
        output: $field_output:ty,
        bounds: { min: $field_bounds_min:expr, max: $field_bounds_max:expr, },
        member_count: $member_count:literal,
        members: [$({
            index: $member_index:literal,
            attrs: [$(#[$member_attrs:meta])*],
            vis: [$member_vis:vis],
            name: $member_name:ident,
            doc: $member_doc:literal,
            name: $member_field_name:ident,
            index: $member_field_index:expr,
            limits: [$({ min: $member_field_limits_min:expr,
                upper: [$($member_field_limits_upper:expr)?], })?],
        },)*],
    };
    assert_eq!(
        template::matcher(&schema.body)?.to_string(),
        expected.to_string()
    );
    Ok(())
}

const LED_SCHEMA: &str = "__led_generate {
    /// GPIO pin.
    pin: ident,
    /// Number of LEDs.
    len: expr,
    /// PIO resource.
    pio: ident = PIO0,
    /// Color curve.
    gamma: expr = Gamma::Srgb,
}";

/// Expands `input` against a `GENERATOR { BODY }` schema, as the generated wrapper would.
fn run(schema: &str, macro_name: &str, input: TokenStream) -> Result<TokenStream> {
    let Schema { generator, body } = syn::parse_str(schema)?;
    expand_parts(macro_name, &quote!(#generator), &body, input)
}

fn pretty(tokens: TokenStream) -> Result<String> {
    Ok(prettyplease::unparse(&syn::parse2(tokens)?))
}

fn error_message(result: Result<TokenStream>) -> Option<String> {
    result.err().map(|error| {
        error
            .into_iter()
            .map(|error| error.to_string())
            .collect::<Vec<_>>()
            .join("\n")
    })
}

#[test]
fn expand_fills_defaults_in_schema_order() -> Result<()> {
    let input = quote! {
        #[derive(Debug)]
        pub(crate) Status { len: 1 + 2, pin: PIN_3 }
    };
    let doc = "Generated by `led!`.\n\n\
        | Field | Value |\n| ----- | ----- |\n\
        | `pin` | `PIN_3` |\n\
        | `len` | `1 + 2` |\n\
        | `pio` | `PIO0` (default) |\n\
        | `gamma` | `Gamma::Srgb` (default) |\n";
    let expected = quote! {
        __led_generate! {
            attrs: [#[derive(Debug)]],
            vis: [pub(crate)],
            name: Status,
            doc: #doc,
            pin: PIN_3,
            len: 1 + 2,
            pio: PIO0,
            gamma: Gamma::Srgb,
        }
    };
    assert_eq!(pretty(expected)?, pretty(run(LED_SCHEMA, "led", input)?)?);
    Ok(())
}

