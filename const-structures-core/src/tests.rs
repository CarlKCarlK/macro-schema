/// `GENERATOR { BODY }`, the shape the generator form of `define!` uses.
struct Schema {
    generator: Path,
    body: BodySpec,
}

impl Parse for Schema {
    fn parse(input: ParseStream) -> Result<Self> {
        let generator = input.parse()?;
        let content;
        braced!(content in input);
        let body = parse_body(&content)?;
        Ok(Self { generator, body })
    }
}

const LED_SCHEMA: &str = "__led_generate {
    /// GPIO pin.
    pin: ident,
    /// Number of LEDs.
    len: expr,
    /// PIO resource.
    pio: ident = PIO0,
    /// Color curve.
    gamma: expr = Gamma::Srgb,
}";

/// Expands `input` against a `GENERATOR { BODY }` schema, as the generated wrapper would.
fn run(schema: &str, macro_name: &str, input: TokenStream) -> Result<TokenStream> {
    let Schema { generator, body } = syn::parse_str(schema)?;
    expand_parts(
        macro_name,
        &Output::Generator(quote!(#generator)),
        &body,
        input,
    )
}

fn pretty(tokens: TokenStream) -> Result<String> {
    Ok(prettyplease::unparse(&syn::parse2(tokens)?))
}

fn error_message(result: Result<TokenStream>) -> Option<String> {
    result.err().map(|error| {
        error
            .into_iter()
            .map(|error| error.to_string())
            .collect::<Vec<_>>()
            .join("\n")
    })
}

#[test]
fn expand_fills_defaults_in_schema_order() -> Result<()> {
    let input = quote! {
        #[derive(Debug)]
        pub(crate) Status { len: 1 + 2, pin: PIN_3 }
    };
    let doc = "Generated by `led!`.\n\n\
        | Field | Value |\n| ----- | ----- |\n\
        | `pin` | `PIN_3` |\n\
        | `len` | `1 + 2` |\n\
        | `pio` | `PIO0` (default) |\n\
        | `gamma` | `Gamma::Srgb` (default) |\n";
    let expected = quote! {
        __led_generate! {
            attrs: [#[derive(Debug)]],
            vis: [pub(crate)],
            name: Status,
            doc: #doc,
            pin: PIN_3,
            len: 1 + 2,
            pio: PIO0,
            gamma: Gamma::Srgb,
        }
    };
    assert_eq!(pretty(expected)?, pretty(run(LED_SCHEMA, "led", input)?)?);
    Ok(())
}

